@app.get("/")
def health():
    return {
        "status": "ok",
        "docs": "/docs",
        "predict": "/predict",
        "retrain": "/retrain",
    }


@app.post("/predict", response_model=Prediction)
def predict(loan: LoanFeatures):
    """Predict the loan amount for one borrower group."""
    row = pd.DataFrame([loan.model_dump()])
    amount = predict_one_test_row(row, MODEL_PATH)
    model = load_saved_model(MODEL_PATH)
    return Prediction(
        predicted_loan_amount_usd=round(amount, 2),
        model_name=type(model.named_steps["model"]).__name__,
    )


def _prepare_new_rows(frame: pd.DataFrame) -> pd.DataFrame:
    required = FEATURES + [TARGET]
    missing = [column for column in required if column not in frame.columns]
    if missing:
        raise HTTPException(
            status_code=400,
            detail=f"CSV is missing columns: {missing}. Expected {required}.",
        )
    data = frame[required].copy()
    for column in ("country", "sector", "activity", "repayment_interval", "loan_theme_type"):
        data[column] = data[column].astype(str).str.strip()
    data["repayment_interval"] = data["repayment_interval"].str.lower()
    canonical = {sector.casefold(): sector for sector in SECTORS}
    data["sector"] = data["sector"].map(lambda value: canonical.get(value.casefold(), value))
    for column in (
        "term_in_months",
        "borrower_count",
        "female_borrower_share",
        "mpi",
        "rural_pct",
        TARGET,
    ):
        data[column] = pd.to_numeric(data[column], errors="coerce")

    received = len(data)
    valid = (
        data["term_in_months"].between(1, 158)
        & data["borrower_count"].between(1, 50)
        & data["female_borrower_share"].between(0, 1)
        & data["mpi"].between(0, 1)
        & data["rural_pct"].between(0, 100)
        & data[TARGET].between(25, 100000)
        & data["country"].str.len().between(2, 60)
        & data["activity"].str.len().between(2, 80)
        & data["loan_theme_type"].str.len().between(2, 80)
        & data["sector"].isin(SECTORS)
        & data["repayment_interval"].isin(REPAYMENT_INTERVALS)
    )
    data = data.loc[valid].copy()
    if data.empty:
        raise HTTPException(
            status_code=400,
            detail=(
                f"The CSV had {received} rows and none were usable. "
                "Use the same columns as training_data.csv, including loan_amount, "
                "with values inside the /predict ranges."
            ),
        )
    data["term_in_months"] = data["term_in_months"].round().astype(int)
    data["borrower_count"] = data["borrower_count"].round().astype(int)
    return data


@app.post("/retrain")
async def retrain(file: UploadFile = File(...)):
    """Refit the deployed model on an uploaded CSV and use it for /predict.

    The CSV must have the same columns as the training file, including the
    target loan_amount. Uploading the file is the only step. If the saved
    model is SGDRegressor, training continues with partial_fit on the new
    rows. Any other model is refit on the original training rows plus the
    new rows.
    """
    raw = await file.read()
    if not raw:
        raise HTTPException(status_code=400, detail="The uploaded CSV is empty.")
    if len(raw) > 8 * 1024 * 1024:
        raise HTTPException(
            status_code=413,
            detail="CSV is larger than 8 MB. Upload only the new rows.",
        )
    try:
        uploaded = pd.read_csv(io.BytesIO(raw))
    except Exception as exc:
        raise HTTPException(status_code=400, detail=f"Could not read the CSV: {exc}") from exc

    new_rows = _prepare_new_rows(uploaded)
    model = load_saved_model(MODEL_PATH)
    estimator = model.named_steps["model"]
    estimator_name = type(estimator).__name__

    if estimator_name == "SGDRegressor":
        transformed = model.named_steps["preprocess"].transform(new_rows[FEATURES])
        estimator.partial_fit(transformed, new_rows[TARGET].to_numpy())
        detail = "Continued training the saved SGDRegressor with partial_fit on the uploaded rows."
        rows_in_fit = int(len(new_rows))
    else:
        if not TRAIN_PATH.exists():
            raise HTTPException(
                status_code=500,
                detail="training_data.csv is missing, so the model cannot be refit.",
            )
        original = pd.read_csv(TRAIN_PATH)
        combined = pd.concat([original, new_rows], ignore_index=True)
        model.fit(combined[FEATURES], combined[TARGET])
        detail = "Refit the saved model on the original training rows plus the uploaded rows."
        rows_in_fit = int(len(combined))

    joblib.dump(model, MODEL_PATH, compress=3)
    remember_model(model, MODEL_PATH)
    return {
        "model_name": estimator_name,
        "rows_uploaded": int(len(new_rows)),
        "rows_in_fit": rows_in_fit,
        "message": detail,
        "persistence": (
            "Subsequent /predict calls use this model without a redeploy. "
            "Render's free plan deletes local file changes when the service "
            "sleeps or restarts, so the next cold start loads the model committed in the repository."
        ),
    }
