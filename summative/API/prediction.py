"""Kiva loan-amount API.

POST /predict returns a recommended loan amount in USD.
POST /retrain fits the saved model on an uploaded CSV and starts using it.
GET /docs is the Swagger UI generated by FastAPI.

On Render, the service root is this folder. The free plan sleeps after
15 minutes without traffic and discards local file changes when it
sleeps, restarts, or redeploys. Startup therefore loads best_model.pkl
from the repository. A retrained model is used until that happens.
"""

import io
import os
from typing import Literal

import joblib
import pandas as pd
from fastapi import FastAPI, File, HTTPException, UploadFile
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, ConfigDict, Field, field_validator

from model_io import (
    FEATURES,
    MODEL_PATH,
    TARGET,
    TRAIN_PATH,
    load_saved_model,
    predict_one_test_row,
    remember_model,
)

SECTORS = (
    "Agriculture",
    "Arts",
    "Clothing",
    "Construction",
    "Education",
    "Entertainment",
    "Food",
    "Health",
    "Housing",
    "Manufacturing",
    "Personal Use",
    "Retail",
    "Services",
    "Transportation",
    "Wholesale",
)
REPAYMENT_INTERVALS = ("weekly", "monthly", "irregular", "bullet")


class LoanFeatures(BaseModel):
    """One field per model input, with the type and range checked before prediction.

    Numeric bounds follow the Pydantic fields guide (Field(ge=..., le=...))
    and match values observed in the Kiva training rows.
    """

    model_config = ConfigDict(
        json_schema_extra={
            "examples": [
                {
                    "country": "Kenya",
                    "sector": "Agriculture",
                    "activity": "Farming",
                    "repayment_interval": "monthly",
                    "loan_theme_type": "General",
                    "term_in_months": 14,
                    "borrower_count": 1,
                    "female_borrower_share": 1.0,
                    "mpi": 0.06,
                    "rural_pct": 69,
                }
            ]
        }
    )

    country: str = Field(
        min_length=2,
        max_length=60,
        description="Borrower country, for example Kenya or Philippines.",
    )
    sector: Literal[
        "Agriculture",
        "Arts",
        "Clothing",
        "Construction",
        "Education",
        "Entertainment",
        "Food",
        "Health",
        "Housing",
        "Manufacturing",
        "Personal Use",
        "Retail",
        "Services",
        "Transportation",
        "Wholesale",
    ] = Field(description="One of the 15 Kiva sectors.")
    activity: str = Field(
        min_length=2,
        max_length=80,
        description="Business activity, for example Farming or General Store.",
    )
    repayment_interval: Literal["weekly", "monthly", "irregular", "bullet"] = Field(
        description="How the borrower repays: weekly, monthly, irregular, or bullet."
    )
    loan_theme_type: str = Field(
        min_length=2,
        max_length=80,
        description="Kiva loan theme, for example General, Agriculture, or Higher Education.",
    )
    term_in_months: int = Field(
        ge=1,
        le=158,
        description="Loan term in months. Kiva terms in this dataset run from 1 to 158.",
    )
    borrower_count: int = Field(
        ge=1,
        le=50,
        description="Number of borrowers in the group. Observed groups have 1 to 50 people.",
    )
    female_borrower_share: float = Field(
        ge=0,
        le=1,
        description="Share of the group who are women, from 0 to 1.",
    )
    mpi: float = Field(
        ge=0,
        le=1,
        description="Multidimensional Poverty Index for the borrower's country or region, from 0 to 1.",
    )
    rural_pct: float = Field(
        ge=0,
        le=100,
        description="Rural population percentage of the borrower's community, from 0 to 100.",
    )

    @field_validator("country", "activity", "loan_theme_type", mode="before")
    @classmethod
    def strip_text(cls, value):
        if isinstance(value, str):
            return value.strip()
        return value

    @field_validator("sector", mode="before")
    @classmethod
    def canonical_sector(cls, value):
        if not isinstance(value, str):
            return value
        text = value.strip()
        for sector in SECTORS:
            if text.casefold() == sector.casefold():
                return sector
        return text

    @field_validator("repayment_interval", mode="before")
    @classmethod
    def canonical_repayment(cls, value):
        if isinstance(value, str):
            return value.strip().lower()
        return value


class Prediction(BaseModel):
    predicted_loan_amount_usd: float = Field(
        description="Recommended loan amount in US dollars."
    )
    model_name: str


def _allowed_origins() -> list[str]:
    # What this allows
    # -----------------
    # Browser calls from this Render service and from local development
    # pages, including a Flutter web dev server on port 8080.
    # Methods are GET, POST, and OPTIONS. Headers are Accept,
    # Authorization, and Content-Type. Credentials are allowed only for
    # the origins listed below.
    #
    # What this restricts
    # -------------------
    # Every other website is rejected. Origins, methods, and headers are
    # written out one by one. The wildcard "*" is not used.
    #
    # Why
    # ---
    # A Flutter mobile app is not a browser, so CORS does not restrict it.
    # This middleware only controls which websites may call the API.
    # The service is a public Render URL. A wildcard origin would let any
    # website read predictions from a visitor's browser. Render sets
    # RENDER_EXTERNAL_URL to this service's own https origin; that exact
    # value is added when it is present so the deployed host is allowed
    # without opening the API to every site.
    origins = [
        "https://kiva-loan-amount.onrender.com",
        "http://localhost",
        "http://localhost:8080",
        "http://127.0.0.1:8080",
        "http://localhost:3000",
        "http://127.0.0.1:3000",
        "http://localhost:5000",
        "http://127.0.0.1:5000",
    ]
    render_origin = os.environ.get("RENDER_EXTERNAL_URL", "").strip().rstrip("/")
    if render_origin.startswith("https://") and render_origin.endswith(".onrender.com"):
        if render_origin not in origins:
            origins.append(render_origin)
    return origins


app = FastAPI(
    title="Kiva loan amount API",
    description=(
        "Recommends a Kiva loan amount in USD for a field-partner loan officer. "
        "A wrong type, a missing field, or an out-of-range number is rejected "
        "before the model runs."
    ),
    version="1.0.0",
)

# What this allows: browser calls from this Render service and from local
# development pages, including a Flutter web dev server on port 8080.
# Methods are GET, POST, and OPTIONS. Headers are Accept, Authorization,
# and Content-Type. Credentials are allowed only for the origins below.
# What this restricts: every other website. Origins, methods, and headers
# are listed one by one. The wildcard "*" is not used.
# Why: a Flutter mobile app is not a browser, so CORS does not restrict it.
